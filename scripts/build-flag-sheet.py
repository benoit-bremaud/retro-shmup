"""Packs the famfamfam 16 x 11 flags into one sheet and writes its code index (ADR-0028).

Development only, not part of the build: run once when the set changes, then commit the two
outputs. Usage: python3 -I scripts/build-flag-sheet.py <dir of famfamfam dist/png> <repo root>
"""

import sys
from pathlib import Path

from PIL import Image

CELL_W, CELL_H, COLUMNS = 16, 11, 16


def main(source: Path, root: Path) -> None:
    codes_file = root / 'src/domain/hall-of-fame/country-codes.ts'
    text = codes_file.read_text()
    body = text[text.index('(\n') : text.index(').split')]
    allowed = sorted(''.join(body.split("'")[1::2]).split())
    codes = [c for c in allowed if (source / f'{c.lower()}.png').is_file()]
    rows = (len(codes) + COLUMNS - 1) // COLUMNS
    sheet = Image.new('RGBA', (COLUMNS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
    for index, code in enumerate(codes):
        flag = Image.open(source / f'{code.lower()}.png').convert('RGBA')
        flag = flag.crop((0, 0, min(flag.width, CELL_W), min(flag.height, CELL_H)))
        x = (index % COLUMNS) * CELL_W + (CELL_W - flag.width) // 2
        y = (index // COLUMNS) * CELL_H + (CELL_H - flag.height) // 2
        sheet.paste(flag, (x, y))
    sheet.save(root / 'public/assets/sprites/flags.png', optimize=True)
    lines = [' '.join(codes[i : i + 24]) for i in range(0, len(codes), 24)]
    joined = " ' +\n  '".join(lines)
    (root / 'src/adapters/flag-codes.ts').write_text(
        '// Generated by scripts/build-flag-sheet.py (ADR-0028): do not edit by hand.\n'
        '/** The codes drawn in `flags.png`, in cell order, 16 cells per row. */\n'
        f"export const FLAG_SHEET_CODES: readonly string[] = (\n  '{joined}'\n).split(' ');\n"
    )
    print(f'{len(codes)} flags, {len(allowed) - len(codes)} codes without a file')


if __name__ == '__main__':
    main(Path(sys.argv[1]), Path(sys.argv[2]))
